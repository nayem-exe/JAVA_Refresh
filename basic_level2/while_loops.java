public class while_loops {
    public static void main(String[] args) {
        int i = 0;

        while (i < 5) {
            System.out.println(i);
            i++;
        }

        int count = 3;

        while(count > 0){
            System.out.println("\n"+ count);
            count --;
        }

        System.out.println("Happy new year!");
    }
}
