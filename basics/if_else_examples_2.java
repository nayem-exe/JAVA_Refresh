public class if_else_examples_2 {
    public static void main(String[] args) {
        int myNum = 10;

        if (myNum > 0) {
            System.out.println("The number is Positive.");
        } else if (myNum < 0){
            System.out.println("The number is Negative.");
        }else{
            System.out.println("The number is 0.");
        }

    }
}
