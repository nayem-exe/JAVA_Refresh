public class check_temparature {
    public static void main(String[] args) {
        int temparature = 10;

        if (temparature < 0){
            System.out.println("It's freezing.");
        }else if (temparature < 20){
            System.out.println("It's cold.");
        }else{
            System.out.println("It's warm.");
        }
    }
}
